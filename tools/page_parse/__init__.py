"""Read one documentation page into structured facts.

This package is the page extractor of the knowledge base:
``tools/kbgen`` calls it behind its versioned extractor interface
(``tools/kbgen/extract.py``; see ``docs/kb-design.ja.md``).  It knows
the page templates the corpus contains and returns *only what the
page says*, always with the raw evidence, so a record can be checked
against its source.

Nothing here normalises a declaration: the text is quoted from the
page (whitespace and all), because an include/.def generator has to
see the original.  Two things *are* derived, and are labelled as such:

* ``spacing`` -- ``collapsed`` when the code block lost the spaces
  between tokens (the archived Learn pages sometimes render
  ``HANDLE CreateFile(`` as ``HANDLECreateFile(``); a consumer can
  prefer the same API's declaration from another source.  It is a
  property of the text, not a repair.
* ``field`` -- the requirement label mapped to a stable name
  (``Header file:`` -> ``header``).  The original label is kept.

Module map (each reads one aspect of a page; all take an HTML
fragment or markdown text and return plain dicts/lists):

    _text         bytes/fragment -> text, regions, headings
    _requirements Requirements blocks and listed-function rows
    _evidence     header/membership statements in prose
    _code         reading C code text (spacing, ABI, classification)
    _constants    constant tables, #define/enum rows, ordinals
    _declarations the Syntax-block reader
    _markdown     the sdk-api markdown reader
    _entities     page subject: names/kinds from titles, filenames
    _notes        constraints, .def rules, Unicode, CE notes, OSS
"""

